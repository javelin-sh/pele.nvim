local rendered, cleared, processes = 0, 0, 0
local system = vim.system
vim.system = function(command, options, callback)
  if command[2]:match('render.mjs$') then processes = processes + 1 end
  return system(command, options, callback)
end
package.loaded.image = { from_file = function(path, options)
  assert(vim.fn.filereadable(path) == 1)
  assert(options.with_virtual_padding)
  assert(options.y == 2, 'preview must anchor to the last source line, not the concealable fence')
  assert(options.render_offset_top == 1, 'preview must start below the source')
  return { render = function() rendered = rendered + 1 end, clear = function() cleared = cleared + 1 end }
end }
